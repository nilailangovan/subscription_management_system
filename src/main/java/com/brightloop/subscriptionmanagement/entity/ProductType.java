package com.brightloop.subscriptionmanagement.entity;

/**
 * Represents the category or type of a Product.
 *
 * - SERVICE  : Intangible services (e.g. consulting, support, maintenance).
 * - GOODS    : Physical items (e.g. hardware, accessories).
 * - SOFTWARE : Software licenses, subscriptions, digital tools.
 */
public enum ProductType {
    SERVICE,
    GOODS,
    SOFTWARE
}

